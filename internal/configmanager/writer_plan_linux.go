//go:build linux

package configmanager

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

// WriterUnitDropIn provisions filesystem access exclusively from the root-owned
// resource registry. It never grants filesystem access to the unprivileged managers.
func WriterUnitDropIn(registry *Registry, checkFiles bool) ([]byte, error) {
	if err := ValidateRegistry(registry); err != nil {
		return nil, err
	}
	dirs := map[string]bool{}
	for _, r := range registry.Resources {
		if r.PrivilegedWrite {
			if r.Profile != "application" && r.Profile != "database" && r.Profile != "network" {
				return nil, fmt.Errorf("configwriter: unsupported profile")
			}
			if r.ValidatorID != "" {
				return nil, fmt.Errorf("configwriter: privileged resources cannot use application validators")
			}
			if err := ValidateWriterPath(r.Path); err != nil {
				return nil, fmt.Errorf("configwriter: resource %s: %w", r.ID, err)
			}
			if checkFiles {
				data, _, err := readManagedFile(r.Path)
				if err != nil {
					return nil, fmt.Errorf("configwriter: resource %q, file %q: %w", r.ID, r.Path, err)
				}
				doc, err := parseDocument(r.Format, data)
				if err != nil {
					return nil, fmt.Errorf("configwriter: resource %q, file %q: %w", r.ID, r.Path, err)
				}
				if err := validateCompleteDocument(r, doc); err != nil {
					return nil, err
				}
				if _, err := captureMetadata(r.Path); err != nil {
					return nil, err
				}
			}
			if r.Access == AccessReadWrite {
				dirs[filepath.Dir(r.Path)] = true
			}
		}
	}
	names := []string{}
	for name := range dirs {
		names = append(names, name)
	}
	sort.Strings(names)
	text := "# Generated by SafeTerm from root-owned resources.json.\n[Service]\nReadWritePaths=\nReadWritePaths=" + WriterState + "\n"
	for _, name := range names {
		text += "ReadWritePaths=" + name + "\n"
	}
	return []byte(strings.TrimSpace(text) + "\n"), nil
}
