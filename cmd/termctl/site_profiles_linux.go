const profileUnitMarker = "# Generated by SafeTerm profile compiler.\n"
const profileGatewayDropIn = "/etc/systemd/system/safeterm-gateway.service.d/60-site-runners.conf"

func profileService(name string) string { return "site-" + name }
func managedServiceUnit(name string) string {
	if unit := serviceUnits[name]; unit != "" {
		return unit
	}
	if strings.HasPrefix(name, "site-") && siteconfig.SiteName.MatchString(strings.TrimPrefix(name, "site-")) {
		return siteconfig.Unit(strings.TrimPrefix(name, "site-"))
	}
	return ""
}
func (r *catalogRuntime) runtimeServices() ([]string, error) {
	result := append([]string{}, serviceOrder...)
	if !r.managedProfiles {
		return result, nil
	}
	cfg, err := r.verified(r.live)
	if err != nil {
		return nil, err
	}
	dynamic := []string{}
	for _, p := range cfg.Profiles {
		if p.Template != "" {
			dynamic = append(dynamic, profileService(string(p.Name)))
		}
	}
	sort.Strings(dynamic)
	index := 0
	for result[index] != "gateway" {
		index++
	}
	result = append(result[:index], append(dynamic, result[index:]...)...)
	return result, nil
}
func (r *catalogRuntime) servicePresent(name string) bool {
	if !strings.HasPrefix(name, "site-") {
		return true
	}
	cfg, err := r.verified(r.live)
	if err != nil {
		return false
	}
	for _, p := range cfg.Profiles {
		if p.Template != "" && profileService(string(p.Name)) == name {
			return true
		}
	}
	return false
}
func (r *catalogRuntime) ensureProfileUser(p config.ProfileDefinition, checkOnly bool) error {
	name := p.RunAsUser
	root := "/var/lib/safeterm-installer/site-users"
	marker := filepath.Join(root, name)
	account, err := user.Lookup(name)
	if err == nil {
		if err := catalogSecureDirectory(root); err != nil {
			return err
		}
		markerData, err := catalogRead(marker)
		if err != nil {
			return fmt.Errorf("reserved profile account %s exists without a SafeTerm ownership marker", name)
		}
		fieldsMarker := strings.Split(strings.TrimSpace(string(markerData)), "\n")
		if len(fieldsMarker) < 2 || fieldsMarker[0] != name || fieldsMarker[1] != string(siteconfig.Base(p)) {
			return fmt.Errorf("profile %s must retain its original base template; choose a new name for another base", p.Name)
		}
		if len(fieldsMarker) == 3 && fieldsMarker[2] != account.Uid {
			return fmt.Errorf("profile %s UID changed outside SafeTerm", p.Name)
		}
		uid, e := strconv.ParseUint(account.Uid, 10, 32)
		if e != nil || uid == 0 || uid >= 1000 {
			return fmt.Errorf("profile account %s must be an unprivileged system UID", name)
		}
		data, e := r.run("/usr/bin/getent", "passwd", name)
		if e != nil {
			return e
		}
		fields := strings.Split(strings.TrimSpace(string(data)), ":")
		gateway, e := user.LookupGroup("safeterm-gateway")
		if e != nil {
			return e
		}
		if len(fields) != 7 || fields[0] != name || fields[3] != gateway.Gid || fields[5] != "/nonexistent" || fields[6] != "/usr/sbin/nologin" {
			return fmt.Errorf("unsafe existing profile account %s", name)
		}
		groups, e := r.run("/usr/bin/id", "-Gn", name)
		if e != nil {
			return e
		}
		permitted := map[string]bool{"safeterm-gateway": true, "safeterm-audit": true}
		if siteconfig.Base(p) == config.ProfileLogReader {
			permitted["adm"] = true
		}
		for _, group := range strings.Fields(string(groups)) {
			if !permitted[group] {
				return fmt.Errorf("profile account %s has unexpected group %s", name, group)
			}
		}
		shadow, e := r.run("/usr/bin/getent", "shadow", name)
		if e != nil {
			return e
		}
		credential := strings.Split(strings.TrimSpace(string(shadow)), ":")
		if len(credential) < 2 || credential[0] != name || (!strings.HasPrefix(credential[1], "!") && !strings.HasPrefix(credential[1], "*")) {
			return fmt.Errorf("profile account %s must remain password-locked", name)
		}
		if !checkOnly && len(fieldsMarker) == 2 {
			return catalogAtomicFile(marker, []byte(name+"\n"+string(siteconfig.Base(p))+"\n"+account.Uid+"\n"), 0600)
		}
		return nil
	}
	if _, ok := err.(user.UnknownUserError); !ok {
		return err
	}
	if existing, e := catalogRead(marker); e == nil {
		fields := strings.Split(strings.TrimSpace(string(existing)), "\n")
		if len(fields) != 2 || fields[0] != name || fields[1] != string(siteconfig.Base(p)) {
			return fmt.Errorf("reserved profile account %s was removed or changed; refusing UID reuse", name)
		}
	} else if !os.IsNotExist(e) {
		return e
	}
	if checkOnly {
		return nil
	}
	if err := os.MkdirAll(root, 0700); err != nil {
		return err
	}
	if err := catalogSecureDirectory(root); err != nil {
		return err
	}
	// A provisional marker makes account creation retryable after a crash.
	if err := catalogAtomicFile(marker, []byte(name+"\n"+string(siteconfig.Base(p))+"\n"), 0600); err != nil {
		return err
	}
	groups := "safeterm-audit"
	if siteconfig.Base(p) == config.ProfileLogReader {
		groups += ",adm"
	}
	_, err = r.run("/usr/sbin/useradd", "--system", "--no-create-home", "--home-dir", "/nonexistent", "--shell", "/usr/sbin/nologin", "--gid", "safeterm-gateway", "--groups", groups, name)
	if err != nil {
		return err
	}
	account, err = user.Lookup(name)
	if err != nil {
		return err
	}
	return catalogAtomicFile(marker, []byte(name+"\n"+string(siteconfig.Base(p))+"\n"+account.Uid+"\n"), 0600)
}
func (r *catalogRuntime) reconcileProfiles(cfg *config.Config) error {
	if !r.managedProfiles {
		return nil
	}
	if err := siteconfig.ValidateCatalog(cfg); err != nil {
		return err
	}
	root := "/etc/systemd/system"
	if err := catalogSecureDirectory(root); err != nil {
		return err
	}
	desired := map[string]string{}
	custom := []string{}
	builtin := map[config.RunnerProfile]string{config.ProfileDiagnostics: serviceUnits["diagnostics"], config.ProfileNetworkObserver: serviceUnits["network"], config.ProfileLogReader: serviceUnits["logs"], config.ProfileServiceManager: serviceUnits["services"]}
	for _, p := range cfg.Profiles {
		unit := builtin[p.Name]
		if p.Template != "" {
			if err := r.ensureProfileUser(p, false); err != nil {
				return err
			}
			unit = siteconfig.Unit(string(p.Name))
			custom = append(custom, unit)
		}
		body, err := siteconfig.RunnerUnit(p)
		if err != nil {
			return err
		}
		desired[unit] = profileUnitMarker + body
	}
	existing, err := filepath.Glob(filepath.Join(root, "safeterm-runner-site-*.service"))
	if err != nil {
		return err
	}
	for _, path := range existing {
		data, err := catalogRead(path)
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(data), profileUnitMarker) {
			return fmt.Errorf("reserved site unit is not generated by SafeTerm: %s", path)
		}
		if _, keep := desired[filepath.Base(path)]; !keep {
			if _, err = r.run("/usr/bin/systemctl", "stop", filepath.Base(path)); err != nil {
				return err
			}
			if _, err = r.run("/usr/bin/systemctl", "disable", filepath.Base(path)); err != nil {
				return err
			}
			if err = os.Remove(path); err != nil {
				return err
			}
		}
	}
	for unit, body := range desired {
		path := filepath.Join(root, unit)
		if strings.HasPrefix(unit, "safeterm-runner-site-") {
			if data, err := catalogRead(path); err == nil && !strings.HasPrefix(string(data), profileUnitMarker) {
				return fmt.Errorf("refusing to replace unmanaged unit %s", unit)
			} else if err != nil && !os.IsNotExist(err) {
				return err
			}
		}
		if err := catalogAtomicFile(path, []byte(body), 0644); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(filepath.Dir(profileGatewayDropIn), 0755); err != nil {
		return err
	}
	if err := catalogSecureDirectory(filepath.Dir(profileGatewayDropIn)); err != nil {
		return err
	}
	sort.Strings(custom)
	text := profileUnitMarker + "[Unit]\n"
	if len(custom) > 0 {
		text += "Requires=" + strings.Join(custom, " ") + "\nAfter=" + strings.Join(custom, " ") + "\n"
	}
	if err := catalogAtomicFile(profileGatewayDropIn, []byte(text), 0644); err != nil {
		return err
	}
	_, err = r.run("/usr/bin/systemctl", "daemon-reload")
	return err
}

func registerSiteServices(dir string) error {
	cfg, err := config.LoadConfig(layout.Catalog(dir))
	if err != nil {
		return err
	}
	if err = integrity.VerifyCatalogFiles(cfg, layout.PublicKey(layout.Catalog(dir)), filepath.Join(layout.Catalog(dir), "catalog.sig")); err != nil {
		return err
	}
	for _, p := range cfg.Profiles {
		if p.Template == "" {
			continue
		}
		if err = siteconfig.ValidateProfile(p); err != nil {
			return err
		}
		name := profileService(string(p.Name))
		if serviceUnits[name] != "" {
			continue
		}
		serviceUnits[name] = siteconfig.Unit(string(p.Name))
		index := 0
		for serviceOrder[index] != "gateway" {
			index++
		}
		serviceOrder = append(serviceOrder[:index], append([]string{name}, serviceOrder[index:]...)...)
	}
	return nil
}
